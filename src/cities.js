// The cities existing in a year: [{ lon, lat, name, rank }].
export function citiesIn(year) {
  const out = []
  for (const [lat, lon, spans] of CITIES) {
    const s = spans.find(([a, b]) => a <= year && year <= b)
    if (s) out.push({ lon, lat, name: s[2], rank: s[3] })
  }
  return out
}
